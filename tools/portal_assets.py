"""Embed the local wireless portal as reproducible gzip resources."""
from pathlib import Path
import gzip


def generate(output, root):
    root, output = Path(root), Path(output)
    files = sorted(p for p in root.rglob('*') if p.suffix in ('.html', '.css', '.js', '.svg') or p.name.startswith('LICENSE'))
    lines = ['/* Generated by tools/portal_assets.py. */', '#include "portal_assets.h"']
    entries = []
    for index, source in enumerate(files):
        data = gzip.compress(source.read_bytes(), compresslevel=9, mtime=0)
        lines.append(f'static const unsigned char resource_{index}[] __attribute__((section(".EPD_WEB"), aligned(4))) = {{')
        lines += [','.join(f'0x{x:02x}' for x in data[n:n+24]) + ',' for n in range(0,len(data),24)]
        lines.append('};')
        url = '/' + source.relative_to(root).as_posix()
        mime = {'.js':'text/javascript', '.html':'text/html', '.css':'text/css', '.svg':'image/svg+xml'}.get(source.suffix, 'text/plain; charset=utf-8')
        entries.append(f'{{"{url}","{mime}",resource_{index},sizeof(resource_{index})}}')
    lines.append('const portal_asset_t portal_assets[] = {' + ',\n'.join(entries) + '};')
    lines.append('const unsigned portal_asset_count = sizeof(portal_assets)/sizeof(*portal_assets);')
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines) + '\n', encoding='utf-8')


def action(target, source, env):
    generate(str(target[0]), env['PORTAL_ASSETS_ROOT'])
    return 0
