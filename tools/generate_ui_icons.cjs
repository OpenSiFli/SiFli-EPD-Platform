/* Rasterize the checked-in SVG selection for the SDK EZIP resource builder. */
const fs = require('node:fs');
const path = require('node:path');
const {renderIcon} = require('./icon_raster.cjs');

const root = path.resolve(__dirname, '..');
const sourceDir = path.join(root, 'assets/icons');
const manifest = require('../assets/icons/manifest.json');

function pruneIcons(output, names) {
    for (const entry of fs.readdirSync(output, {withFileTypes: true})) {
        const match = /^ui_icon_(.+)\.png$/.exec(entry.name);
        if (entry.isFile() && match && !names.has(match[1]))
            fs.unlinkSync(path.join(output, entry.name));
    }
}

async function main(args = process.argv.slice(2)) {
    let selected = null;
    if (args.length) {
        if (args.length !== 2 || args[0] !== '--only' || !args[1])
            throw new Error('Usage: node tools/generate_ui_icons.cjs [--only name1,name2]');
        selected = new Set(args[1].split(','));
        for (const name of selected)
            if (!manifest.icons.some(icon => icon.name === name))
                throw new Error(`Unknown icon: ${name}`);
    }
    const output = path.join(root, 'assets/ezip/icons');
    fs.mkdirSync(output, {recursive: true});
    const cache = new Map();
    async function png(source, size, visibleHeight) {
        const key = `${source}:${size}:${visibleHeight || 0}`;
        if (!cache.has(key)) cache.set(key, await renderIcon(path.join(sourceDir, source), size, visibleHeight));
        return cache.get(key);
    }
    let header = '/* Generated by tools/generate_ui_icons.cjs. */\n';
    header += '#ifndef UI_ICONS_H\n#define UI_ICONS_H\n#include "lvgl.h"\n';
    const names = new Set();
    for (const icon of manifest.icons) {
        if (names.has(icon.name)) throw new Error(`Duplicate icon: ${icon.name}`);
        names.add(icon.name);
        if (!selected || selected.has(icon.name))
            fs.writeFileSync(path.join(output, `ui_icon_${icon.name}.png`), await png(icon.source, icon.size, icon.visible_height));
        header += `extern const lv_image_dsc_t ui_icon_${icon.name};\n`;
        for (const height of icon.height_variants || []) {
            const name = `${icon.name}_h${height}`;
            if (names.has(name)) throw new Error(`Duplicate icon: ${name}`);
            names.add(name);
            if (!selected || selected.has(icon.name))
                fs.writeFileSync(path.join(output, `ui_icon_${name}.png`), await png(icon.source, icon.size, height));
            header += `extern const lv_image_dsc_t ui_icon_${name};\n`;
        }
    }
    header += '\nstatic inline const lv_image_dsc_t *ui_icon_at_height(const lv_image_dsc_t *icon, unsigned height)\n{\n';
    for (const icon of manifest.icons.filter(icon => icon.height_variants)) {
        header += `    if (icon == &ui_icon_${icon.name}) {\n        switch (height) {\n`;
        for (const height of icon.height_variants)
            header += `        case ${height}: return &ui_icon_${icon.name}_h${height};\n`;
        header += '        default: return icon;\n        }\n    }\n';
    }
    header += '    return icon;\n}\n';
    fs.writeFileSync(path.join(root, 'src/ui/icons/ui_icons.h'), header + '#endif\n');
    if (selected) {
        console.log(`Prepared ${selected.size} UI icons`);
        return;
    }
    pruneIcons(output, names);
    console.log(`Prepared ${manifest.icons.length} platform icons`);
}

module.exports = {pruneIcons};
if (require.main === module) main().catch(error => {console.error(error); process.exitCode = 1;});
