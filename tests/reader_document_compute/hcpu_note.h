static void note_lifecycle_tests(void)
{
    assert(!documents && !wire_data);
    wire_bytes = 0;
    picture_event(BOOK_DOCUMENT_TEXT, 0, 0, 0, 0, "Note \xe4\xb8\xad\xe6\x96\x87", 11);
    picture_event(BOOK_DOCUMENT_NOTE_END, 1, 0, 0, 0, NULL, 0);
    note_wire = wire_data; note_wire_bytes = wire_bytes; wire_data = NULL;
    flow_fixture(false, 20, true); flow_open("note-paused-source");
    document_t *d = view.document;
    const char target[] = "OPS/notes.xhtml#n";
    assert(navigation_append(d, 7, DOCUMENT_LINK, 0, target, sizeof(target), false));
    assert(!conversion_runnable(d) && !d->prefetch_enabled && d->converting);
    document_anchor_t position = d->requested;
    epd_compute_pipe_host_t original_pipe = d->pipe;
    unsigned body_steps = original_pipe->steps;
    uint32_t body_end = d->status.end;
    char output[4097]; bool truncated = false;
    unsigned reads = io_reads, opens = io_opens, pipes = pipe_opens;
    document_note_request_t *n = document_note_request(d, 7); assert(n);
    assert(document_note_take(n, output, sizeof(output), &truncated) == 0);
    assert(reads == io_reads && opens == io_opens && pipes == pipe_opens && !d->cancelled);
    assert(!conversion_runnable(d));
    document_note_request_t *cancelled_note = document_note_request(d, 7); assert(cancelled_note);
    assert(!document_note_request(d, 7));
    document_note_cancel(cancelled_note);
    assert(document_note_take(cancelled_note, output, sizeof(output), &truncated) == -1);
    pump();
    assert(!d->cancelled && !d->status.complete && d->converting && d->pipe == original_pipe);
    assert(original_pipe->steps == body_steps && d->status.end == body_end);
    assert(!memcmp(&position, &d->requested, sizeof(position)));
    assert(document_note_take(n, output, sizeof(output), &truncated) == 1);
    assert(!strcmp(output, "Note \xe4\xb8\xad\xe6\x96\x87") && truncated);
    assert(!n->document->cached && !n->document->cache[0] && !n->document->navigation);
    assert(document_note_take(n, output, 7, &truncated) == 1 && !strcmp(output, "Note ") && truncated);
    document_note_cancel(n); pump();
    assert(documents == d && !d->next);
    assert(original_pipe->steps == body_steps && pipe_opens == pipes + 1);
    unsigned commits = cache_commits;
    n = document_note_request(d, 7); assert(n);
    assert(document_worker_step(&service) && n->document->converting);
    document_note_cancel(n); pump();
    assert(documents == d && !d->next && cache_commits == commits && !d->cancelled);
    n = document_note_request(d, 7); assert(n);
    host_ticks += 10001;
    assert(document_note_take(n, output, sizeof(output), NULL) == -1);
    document_note_cancel(n); pump();
    assert(documents == d && !d->next);
    /* A successful pipe without NOTE_END must not publish partial text. */
    note_wire_bytes -= sizeof(book_document_event_t);
    n = document_note_request(d, 7); assert(n); pump();
    assert(document_note_take(n, output, sizeof(output), NULL) == -1);
    document_note_cancel(n); pump();
    assert(d->pipe == original_pipe && original_pipe->steps == body_steps);
    unsigned opened = pipe_opens;
    document_prefetch_enable(d, true); pump();
    assert(d->status.complete && !d->status.result && pipe_opens == opened && !d->cancelled);
    assert(!memcmp(&position, &d->requested, sizeof(position)));
    lifecycle_close(d); memset(&view, 0, sizeof(view));
    free(wire_data); wire_data = NULL; wire_bytes = 0;
    free(note_wire); note_wire = NULL; note_wire_bytes = 0;
    pipe_events_per_step = pipe_step_ticks = 0;
    puts("HCPU notes: paused source, prefetch off, no UI I/O, bounded queue, UTF8, timeout, cancel, terminal, ownership passed");
}
