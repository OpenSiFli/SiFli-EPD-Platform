const fs = require('node:fs');
const path = require('node:path');
const sharp = require('sharp');

const icons = [
    {name: 'sessions', size: 36},
    {name: 'new', size: 36},
    {name: 'speaker', size: 36},
    {name: 'globe', size: 28},
    {name: 'microphone', size: 36},
    {name: 'send', size: 36, white: true},
    {name: 'stop', size: 36, white: true},
    {name: 'chevron', size: 20},
    {name: 'welcome', size: 120},
    {name: 'assistant', size: 32},
    {name: 'retry', size: 36},
];
const scales = [90, 95, 100, 110, 120];
const controlsDir = path.join(__dirname, 'controls');

function pixelSize(icon, scale) {
    return Math.round(icon.size * scale / 200) * 2;
}

function packI4(raw, size, color) {
    const data = Buffer.alloc(64 + size * size / 2);
    for (let i = 0; i < 16; ++i) {
        data.fill(color, i * 4, i * 4 + 3);
        data[i * 4 + 3] = i * 17;
    }
    for (let i = 0; i < size * size; ++i)
        data[64 + (i >> 1)] |= Math.round(raw[i * 4 + 3] / 17) << (i % 2 ? 0 : 4);
    return data;
}

function unpackI4(data, size) {
    const raw = Buffer.alloc(size * size * 4);
    for (let i = 0; i < size * size; ++i) {
        const index = (data[64 + (i >> 1)] >> (i % 2 ? 0 : 4)) & 15;
        data.copy(raw, i * 4, index * 4, index * 4 + 4);
    }
    return raw;
}

function imageSource(name, size, data) {
    let c = `static const uint8_t data_${name}[] = {\n`;
    for (let i = 0; i < data.length; i += 24)
        c += '    ' + Array.from(data.subarray(i, i + 24), v => '0x' + v.toString(16).padStart(2, '0')).join(',') + ',\n';
    c += `};
static const lv_image_dsc_t icon_${name} = {
    .header = {.magic=LV_IMAGE_HEADER_MAGIC, .cf=LV_COLOR_FORMAT_I4, .w=${size}, .h=${size}, .stride=${size / 2}},
    .data_size=sizeof(data_${name}), .data=data_${name}
};
`;
    return c;
}

async function contactSheet(images) {
    const labelWidth = 180, columnWidth = 320, headerHeight = 116;
    const rowHeights = icons.map(icon => icon.name === 'welcome' ? 204 : 100);
    const width = labelWidth + columnWidth * scales.length;
    const height = headerHeight + rowHeights.reduce((sum, value) => sum + value, 0) + 28;
    let svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
<rect width="${width}" height="${height}" fill="white"/>
<g font-family="Arial, sans-serif" fill="#222">
<text x="24" y="34" font-size="23" font-weight="bold">AI chat icons</text>
<text x="24" y="58" font-size="13" fill="#666">I4 / 16 alpha levels / native pixel sizes / white symbols shown on button backgrounds</text>
`;
    for (let column = 0; column < scales.length; ++column) {
        const x = labelWidth + column * columnWidth;
        svg += `<text x="${x + columnWidth / 2}" y="86" text-anchor="middle" font-size="17">${scales[column]}%</text>
<text x="${x + 80}" y="106" text-anchor="middle" font-size="12" fill="#666">active=true</text>
<text x="${x + 240}" y="106" text-anchor="middle" font-size="12" fill="#666">active=false</text>\n`;
    }
    let y = headerHeight;
    for (let row = 0; row < icons.length; ++row) {
        const icon = icons[row], rowHeight = rowHeights[row];
        svg += `<path d="M16 ${y}H${width - 16}" stroke="#e5e5e5"/>
<text x="24" y="${y + rowHeight / 2 - 2}" font-size="16">${icon.name}</text>
<text x="24" y="${y + rowHeight / 2 + 19}" font-size="12" fill="#777">base ${icon.size} px</text>\n`;
        for (let column = 0; column < scales.length; ++column) {
            const scale = scales[column], size = pixelSize(icon, scale);
            const x = labelWidth + column * columnWidth;
            const centerY = y + (rowHeight - 20) / 2;
            for (const active of [1, 0]) {
                const centerX = x + (active ? 80 : 240);
                if (icon.white)
                    svg += `<circle cx="${centerX}" cy="${centerY}" r="${Math.round(size * 0.75)}" fill="${active ? '#000' : '#999'}"/>\n`;
                const data = images.get(`${icon.name}_${scale}_${active}`);
                const png = await sharp(unpackI4(data, size), {raw: {width: size, height: size, channels: 4}}).png().toBuffer();
                svg += `<image x="${centerX - size / 2}" y="${centerY - size / 2}" width="${size}" height="${size}" href="data:image/png;base64,${png.toString('base64')}"/>\n`;
            }
            svg += `<text x="${x + columnWidth / 2}" y="${y + rowHeight - 8}" text-anchor="middle" font-size="12" fill="#777">${size} x ${size} px</text>\n`;
        }
        y += rowHeight;
    }
    return svg + '</g>\n</svg>\n';
}

async function main() {
    let c = '/* Generated by assets/generate_controls.cjs. */\n#include "chat_icons.h"\n#include "src/draw/lv_image_decoder_private.h"\n';
    const images = new Map();
    for (const icon of icons) for (const scale of scales) {
        const size = pixelSize(icon, scale);
        const {data: raw, info} = await sharp(path.join(controlsDir, icon.name + '.svg'), {density: 384})
            .resize(size, size).toColourspace('srgb').ensureAlpha().raw().toBuffer({resolveWithObject: true});
        if (info.channels !== 4 || info.width !== size || info.height !== size)
            throw new Error(`Unexpected image format: ${icon.name} at ${scale}%`);
        for (const active of [0, 1]) {
            const color = icon.white ? 0xff : active ? 0 : 0x99;
            const data = packI4(raw, size, color);
            const name = `${icon.name}_${scale}_${active}`;
            images.set(name, data);
            c += imageSource(name, size, data);
        }
    }
    c += `static const lv_image_dsc_t *const images[CHAT_ICON_COUNT][${scales.length}][2] = {\n`;
    for (const icon of icons)
        c += `    [CHAT_ICON_${icon.name.toUpperCase()}] = {` + scales.map(scale => '{' + [0, 1].map(active => `&icon_${icon.name}_${scale}_${active}`).join(',') + '}').join(',') + '},\n';
    c += `};
const lv_image_dsc_t *chat_icon(chat_icon_t icon, unsigned scale, bool active)
{
    unsigned index = scale <= 90 ? 0 : scale <= 95 ? 1 : scale <= 100 ? 2 : scale <= 110 ? 3 : 4;
    unsigned icon_index = (unsigned)icon < CHAT_ICON_COUNT ? (unsigned)icon : CHAT_ICON_SESSIONS;
    return images[icon_index][index][active ? 1 : 0];
}
void chat_icons_release(void)
{
    for (unsigned icon = 0; icon < CHAT_ICON_COUNT; ++icon) for (unsigned scale = 0; scale < ${scales.length}; ++scale) for (unsigned active = 0; active < 2; ++active) {
        lv_image_cache_drop(images[icon][scale][active]);
        lv_image_header_cache_drop(images[icon][scale][active]);
    }
}
`;
    const sheet = await contactSheet(images);
    fs.writeFileSync(path.join(__dirname, '../src/chat_icons.c'), c);
    fs.writeFileSync(path.join(controlsDir, 'contact-sheet.svg'), sheet);
    console.log(`Generated ${icons.length} chat icons at ${scales.length} scales in two states (${images.size} I4 images).`);
    for (const icon of icons)
        console.log(`${icon.name}: ${scales.map(scale => `${scale}%=${pixelSize(icon, scale)}px`).join(', ')}`);
    console.log('Contact sheet: ' + path.join(controlsDir, 'contact-sheet.svg'));
}

main().catch(error => { console.error(error); process.exitCode = 1; });
