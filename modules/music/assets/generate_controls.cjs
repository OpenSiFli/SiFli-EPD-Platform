// Rebuild the music application's bundled MingCute icons; ordinary builds use the saved C files.
const fs = require('node:fs');
const path = require('node:path');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(__dirname, 'controls/manifest.json'), 'utf8'));
const icons = Object.keys(manifest.icons).map(name => ({name, source:name, size:48}));
icons.push({name:'play_large', source:'play', size:80}, {name:'pause_large', source:'pause', size:80},
           {name:'music_large', source:'music', size:112});
const scales = [90, 95, 100, 110, 120];
async function main() {
  let c = '/* Generated by assets/generate_controls.cjs. MingCute, Apache-2.0; see assets/controls/manifest.json. */\n#include "music_icons.h"\n';
  for (const icon of icons) {
    for (const scale of scales) {
      const size = Math.round(icon.size * scale / 200) * 2;
      const raw = await sharp(path.join(__dirname, 'controls', icon.source+'.svg')).resize(size,size).ensureAlpha().raw().toBuffer();
      const data = Buffer.alloc(64+size*size/2);
      for(let i=0;i<16;i++) data[i*4+3]=i*17;
      for(let i=0;i<size*size;i++) {
        const alpha=Math.round(raw[i*4+3]/17);
        data[64+(i>>1)] |= alpha << (i%2 ? 0 : 4);
      }
      const name=icon.name+'_'+scale;
      c+='static const uint8_t data_'+name+'[] = {\n';
      for(let i=0;i<data.length;i+=24) c+='    '+Array.from(data.subarray(i,i+24),v=>'0x'+v.toString(16).padStart(2,'0')).join(',')+',\n';
      c+='};\nstatic const lv_image_dsc_t icon_'+name+' = {\n    .header = {.magic=LV_IMAGE_HEADER_MAGIC, .cf=LV_COLOR_FORMAT_I4, .w='+size+', .h='+size+', .stride='+size/2+'},\n    .data_size=sizeof(data_'+name+'), .data=data_'+name+'\n};\n';
    }
  }
  c+='const lv_image_dsc_t *music_icon(music_icon_id_t id, unsigned scale)\n{\n    static const lv_image_dsc_t *const images[MUSIC_ICON_COUNT][5] = {\n';
  for(const icon of icons) c+='        {'+scales.map(s=>'&icon_'+icon.name+'_'+s).join(',')+'},\n';
  c+='    };\n    unsigned index=scale<=90?0:scale<=95?1:scale<=100?2:scale<=110?3:4;\n    return images[id < MUSIC_ICON_COUNT ? id : MUSIC_ICON_MUSIC][index];\n}\n';
  const h='#ifndef MUSIC_ICONS_H\n#define MUSIC_ICONS_H\n#include "lvgl.h"\ntypedef enum {\n'+icons.map(i=>'    MUSIC_ICON_'+i.name.toUpperCase()+',\n').join('')+'    MUSIC_ICON_COUNT\n} music_icon_id_t;\nconst lv_image_dsc_t *music_icon(music_icon_id_t id, unsigned scale);\n#endif\n';
  fs.writeFileSync(path.join(root,'music_icons.c'),c);
  fs.writeFileSync(path.join(root,'music_icons.h'),h);
  console.log('Generated '+icons.length+' icons at '+scales.length+' scales.');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
