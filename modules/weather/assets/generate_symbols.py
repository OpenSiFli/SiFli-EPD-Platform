"""Regenerate the weather module's fixed 32-pixel metric symbols."""

from pathlib import Path

from PIL import Image


ASSETS = Path(__file__).resolve().parent
NAMES = ("humidity", "wind", "visibility", "cloud", "sunrise", "sunset",
         "pressure", "air", "location")


def main():
    out = ["/* Generated by assets/generate_symbols.py. */"]
    out.append("static const uint8_t symbol_pixels[][576] = {")
    for name in NAMES:
        with Image.open(ASSETS / "ezip" / "icons" / f"ui_icon_{name}.png") as image:
            if image.size != (32, 32):
                raise ValueError(f"Unexpected dimensions for {name}")
            alpha = image.convert("RGBA").getchannel("A").tobytes()
        data = bytearray()
        for level in range(16):
            data.extend((0, 0, 0, level * 17))
        levels = [(value + 8) // 17 for value in alpha]
        data.extend(high << 4 | low for high, low in zip(levels[::2], levels[1::2]))
        out.append(f"    {{ /* {name} */")
        for start in range(0, len(data), 24):
            out.append("        " + ",".join(f"0x{b:02x}" for b in data[start:start + 24]) + ",")
        out.append("    },")
    out.extend(("};", "", "static const lv_image_dsc_t symbols[] = {"))
    for index in range(len(NAMES)):
        out.append("    {.header={.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_I4,.w=32,.h=32,.stride=16},")
        out.append(f"     .data_size=sizeof(symbol_pixels[{index}]),.data=symbol_pixels[{index}]}},")
    out.extend(("};", ""))
    (ASSETS.parent / "weather_symbols.inc").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
